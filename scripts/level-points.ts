/**
 * Writes the points of the first levels into a Supabase migration, so that the
 * server scores a solved level without trusting the app. Run it again (and
 * apply the new migration) whenever level generation changes:
 *
 *   npm run level-points
 */
import { writeFileSync } from 'node:fs';
import { levelInfo } from '../src/core/levels';
import { levelPoints } from '../src/online/points';

export const LEVEL_POINTS_COUNT = 5000;
const OUT = 'supabase/migrations/20261027000100_level_points.sql';

const rows: string[] = [];
for (let n = 1; n <= LEVEL_POINTS_COUNT; n++) rows.push(`(${n},${levelPoints(levelInfo(n))})`);

const lines: string[] = [];
for (let k = 0; k < rows.length; k += 20) lines.push(rows.slice(k, k + 20).join(','));
writeFileSync(
  OUT,
  [
    `-- Generated by scripts/level-points.ts: points of levels 1 to ${LEVEL_POINTS_COUNT} (src/online/points.ts).`,
    '-- Beyond them, submit_solve falls back on 4 points for joined edges, 1 otherwise.',
    'truncate public.level_points;',
    'insert into public.level_points (level, points) values',
    lines.join(',\n') + ';',
    '',
  ].join('\n'),
);
console.log(`wrote ${OUT}`);
